// Writes src/server/artifact-fonts.generated.ts: the Golos Text fonts a frame of an artifact loads
// from the root of the pages (docs/plan/88-artifacts.md, Ар30). Run from apps/web after an update
// of @fontsource-variable/golos-text; the test of artifact-platform checks the module is current.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const require = createRequire(import.meta.url)
const dir = join(dirname(require.resolve('@fontsource-variable/golos-text/package.json')), 'files')
const files = {
  'lib-golos-cyr': 'golos-text-cyrillic-wght-normal.woff2',
  'lib-golos-lat': 'golos-text-latin-wght-normal.woff2',
}
let out =
  '// Generated by `node scripts/artifact-fonts.mjs` from @fontsource-variable/golos-text (OFL-1.1): the\n' +
  '// fonts a frame of an artifact loads from the root of the pages (docs/plan/88-artifacts.md, Ар30).\n' +
  '// Bytes in the module so that the standalone server needs no file of node_modules. Do not edit.\n\n' +
  'export const artifactFontSources = {\n'
for (const [label, file] of Object.entries(files))
  out += `  ${JSON.stringify(label)}: {\n    file: ${JSON.stringify(file)},\n    base64:\n      ${JSON.stringify(readFileSync(join(dir, file)).toString('base64'))},\n  },\n`
out += '} as const\n'
writeFileSync(new URL('../src/server/artifact-fonts.generated.ts', import.meta.url), out)
