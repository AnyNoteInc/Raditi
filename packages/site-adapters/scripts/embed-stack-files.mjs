#!/usr/bin/env node
// Writes the constants of every stack in EMBEDDED (stack-files.mjs): the files of infra/<stack>/ a
// preview of the stack gets (docs/plan/53-chat-preview-release.md, Р14, Р15; docs/plan/62, Т12),
// as string constants. The orchestrator image holds the workspace packages and not infra/, and the
// recipe hands the files over as text; infra/<stack>/ stays the one source that CI checks with
// `php -l`.
//
//   node packages/site-adapters/scripts/embed-stack-files.mjs
//
// stack-files.test.ts fails while the constants and the files differ.
import console from 'node:console'
import { writeFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'

import { format, resolveConfig } from 'prettier'

import { EMBEDDED, stackFiles } from './stack-files.mjs'

const root = new URL('../../../', import.meta.url)

for (const [folder, target] of Object.entries(EMBEDDED)) {
  const constants = stackFiles(root, folder).map(
    ({ path, constant, text }) =>
      `/** ${path} */\nexport const ${constant}: string = ${JSON.stringify(text)}\n`,
  )
  const source = [
    `// Generated by packages/site-adapters/scripts/embed-stack-files.mjs from infra/${folder}.`,
    '// Do not edit: change the file there and run the script again.\n',
    ...constants,
  ].join('\n')
  const path = fileURLToPath(new URL(`../${target}`, import.meta.url))
  writeFileSync(path, await format(source, { ...(await resolveConfig(path)), filepath: path }))
  console.log(`wrote ${path}`)
}
