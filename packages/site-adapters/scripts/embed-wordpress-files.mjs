#!/usr/bin/env node
// Writes src/wordpress-preview-files.ts: the files of infra/wordpress a preview of a WordPress
// site gets (docs/plan/53-chat-preview-release.md, Р14, Р15), as string constants. The
// orchestrator image holds the workspace packages and not infra/, and the recipe hands the
// files over as text; infra/wordpress stays the one source that CI checks with `php -l`.
//
//   node packages/site-adapters/scripts/embed-wordpress-files.mjs
//
// wordpress-preview.test.ts fails while the constants and the files differ.
import console from 'node:console'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'

import { format, resolveConfig } from 'prettier'

const root = new URL('../../../', import.meta.url)
const target = new URL('../src/wordpress-preview-files.ts', import.meta.url)

const files = [
  ['raditiContentPhp', 'infra/wordpress/raditi-content.php'],
  ['raditiPreviewPhp', 'infra/wordpress/raditi-preview.php'],
  ['previewWpConfigPhp', 'infra/wordpress/preview-wp-config.php'],
  ['previewApacheConf', 'infra/wordpress/preview-apache.conf'],
]

const constants = files.map(([name, path]) => {
  const text = readFileSync(new URL(path, root), 'utf8')
  return `/** ${path} */\nexport const ${name}: string = ${JSON.stringify(text)}\n`
})
const source = [
  '// Generated by packages/site-adapters/scripts/embed-wordpress-files.mjs from infra/wordpress.',
  '// Do not edit: change the file there and run the script again.\n',
  ...constants,
].join('\n')

const path = fileURLToPath(target)
writeFileSync(path, await format(source, { ...(await resolveConfig(path)), filepath: path }))
console.log(`wrote ${path}`)
