import { chromium } from '<repo>/packages/browser-providers/node_modules/playwright-core/index.mjs'
const [base, user, password] = process.argv.slice(2)
const b = await chromium.launch({ headless: true })
const c = await b.newContext(); const p = await c.newPage()
const bad = []
p.on('response', (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().replace(base, '').slice(0, 100)}`) })
p.on('pageerror', (e) => bad.push(`pageerror ${e.message.slice(0, 140)}`))
p.on('console', (m) => { if (m.type() === 'error') bad.push(`console ${m.text().slice(0, 140)}`) })
await p.goto(`${base}/manager/`, { waitUntil: 'load' })
console.log('login page:', await p.title(), '| lang:', await p.locator('html').getAttribute('lang'))
await p.fill('#modx-login-username', user); await p.fill('#modx-login-password', password)
await p.click('#modx-login-btn, button[name=login]')
await p.waitForTimeout(3500)
console.log('after login:', p.url().replace(base, ''), '|', await p.title())
console.log('cookies:', (await c.cookies()).map((k) => k.name).join(' '))
await p.goto(`${base}/manager/?a=resource/update&id=4`, { waitUntil: 'load' })
await p.waitForTimeout(3500)
console.log('resource:', await p.title(), '| field pagetitle =', await p.locator('input[name=pagetitle]').inputValue().catch((e) => 'NO ' + e.message.slice(0, 60)))
await p.locator('input[name=pagetitle]').fill('Первая новость правка').catch(() => {})
await p.locator('#modx-abtn-save').click().catch((e) => console.log('save', e.message.slice(0, 100)))
await p.waitForTimeout(2500)
console.log('title after save:', await p.title())
console.log('bad:', [...new Set(bad)].slice(0, 14))
await b.close()
